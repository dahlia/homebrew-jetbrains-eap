cask "clion-eap" do
  arch arm: "-aarch64"

  version "2026.3,263.5153.33"
  sha256 arm:   "1420671d730d2377a1eb4c2cf8634c280ba9ad0d21699e156829391df67b932f",
         intel: "7226fb594cb98eca248e01cadfc56fdde1e7d4c740508e67dc954d52535cc662"

  url "https://download.jetbrains.com/cpp/CLion-#{version.csv.second}#{arch}.dmg"
  name "CLion EAP"
  desc "C and C++ IDE (EAP)"
  homepage "https://www.jetbrains.com/clion/nextversion/"

  livecheck do
    url "https://data.services.jetbrains.com/products/releases?code=CL&latest=true&type=eap"
    strategy :json do |json|
      json["CL"]&.map do |release|
        version = release["version"]
        build = release["build"]
        next if version.blank? || build.blank?

        "#{version},#{build}"
      end
    end
  end

  auto_updates true
  depends_on macos: :monterey

  # The application path is often inconsistent between versions
  rename "CLion*.app", "CLion EAP.app"

  app "CLion EAP.app"
  binary "#{appdir}/CLion EAP.app/Contents/MacOS/clion", target: "clion-eap"

  uninstall_postflight_steps do
    remove ["/usr/local/bin/clion", "{{HOMEBREW_PREFIX}}/bin/clion"],
           content_contains: "# see com.intellij.idea.SocketLock for the server side of this interface"
  end

  zap trash: [
    "~/Library/Application Support/JetBrains/CLion#{version.csv.first}",
    "~/Library/Caches/JetBrains/CLion#{version.csv.first}",
    "~/Library/Logs/JetBrains/CLion#{version.csv.first}",
    "~/Library/Preferences/com.jetbrains.CLion-EAP.plist",
    "~/Library/Saved Application State/com.jetbrains.CLion-EAP.savedState",
  ]
end
